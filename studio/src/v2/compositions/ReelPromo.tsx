/**
 * ReelPromo — the 24s / 1920×1080 / 30fps dsh-reel v2 promo film.
 *
 * Scene boundaries + sound anchors live in ../data/timeline.ts.
 * Scenes are self-contained (they read their own Sequence-relative frame), so this
 * file is only the edit list + soundtrack + global finish.
 */

import React from 'react';
import {AbsoluteFill, Audio, Sequence, interpolate, staticFile, useCurrentFrame} from 'remotion';
import {COLORS} from '../tokens';
import {SCENES} from '../data/timeline';
import {S1Hook, S2Hatch, S8Outputs, S9Outro} from '../scenes/hero/HeroScenes';
import {S3MarketOpen, S4Search, S5Install} from '../scenes/market/MarketScenes';
import {S6Handoff, S7Pipeline} from '../scenes/montage/MontageScenes';

const SCENE_MAP: Record<string, React.FC> = {
  S1: S1Hook,
  S2: S2Hatch,
  S3: S3MarketOpen,
  S4: S4Search,
  S5: S5Install,
  S6: S6Handoff,
  S7: S7Pipeline,
  S8: S8Outputs,
  S9: S9Outro,
};

/**
 * Edit-point flashes: the film is a series of scenes (not a true one-take), so each
 * hard cut gets a 5-frame blue/mint bloom to read as an intentional transition.
 */
const CUTS: Array<[number, number]> = [
  [156, 0.2], // S2 -> S3 (enter the DSH window)
  [348, 0.14], // S4 -> S5 (result -> detail)
  [426, 0.11], // S5 -> S6 (installed -> hand-off)
  [462, 0.09], // S6 -> S7 (hand-off -> pipeline)
  [588, 0.17], // S7 -> S8 (render -> world with outputs)
  [660, 0.15], // S8 -> S9 (outputs -> end card)
];

const CutFlash: React.FC = () => {
  const frame = useCurrentFrame();
  let k = 0;
  for (const [cut, amp] of CUTS) {
    const d = frame - cut;
    if (d >= 0 && d < 6) k = Math.max(k, (1 - d / 6) * amp);
  }
  if (k <= 0) return null;
  return (
    <AbsoluteFill style={{pointerEvents: 'none', opacity: k}}>
      <AbsoluteFill
        style={{
          background: `radial-gradient(ellipse at 50% 46%, #FFFFFF 0%, ${COLORS.blue2} 28%, ${COLORS.blue}44 62%, transparent 100%)`,
          mixBlendMode: 'screen',
        }}
      />
    </AbsoluteFill>
  );
};

/** Global finishing: subtle top/bottom letterbox glow + very light scanline-free grain is per scene. */
const Finish: React.FC = () => (
  <AbsoluteFill style={{pointerEvents: 'none'}}>
    <div
      style={{
        position: 'absolute',
        left: 0,
        right: 0,
        top: 0,
        height: 2,
        background: `linear-gradient(90deg, transparent, ${COLORS.blue}66, ${COLORS.mint}44, transparent)`,
        opacity: 0.5,
      }}
    />
  </AbsoluteFill>
);

export const ReelPromo: React.FC = () => {
  return (
    <AbsoluteFill style={{backgroundColor: COLORS.bg0}}>
      {/* One premixed track (24.0s, 48k stereo, generated by scripts/make_sfx_v2.py, encoded to 192k mp3). */}
      <Audio src={staticFile('audio/v2/preview-mix.mp3')} />

      {SCENES.map((scene) => {
        const Comp = SCENE_MAP[scene.id];
        if (!Comp) return null;
        return (
          <Sequence key={scene.id} from={scene.from} durationInFrames={scene.duration} name={`${scene.id}-${scene.title}`}>
            <Comp />
          </Sequence>
        );
      })}

      <Finish />
      <CutFlash />
    </AbsoluteFill>
  );
};
